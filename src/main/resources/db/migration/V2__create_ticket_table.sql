-- Ticket: a numbered token emitted to the attendance queue.
-- Its life cycle is always governed by the status column:
--   WAITING   -> CALLED    (the attendant called the ticket)
--   WAITING   -> CANCELLED (cancelled individually or by clearing the queue)
--   CALLED    -> CANCELLED (cancelled after being called, e.g. client did not show up)
CREATE TABLE tb_ticket (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number       VARCHAR(12)   NOT NULL,
    client_name  VARCHAR(120)  NOT NULL,
    priority     BOOLEAN       NOT NULL,
    status       VARCHAR(20)   NOT NULL,
    issued_at    TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    called_at    TIMESTAMP(9) WITH TIME ZONE,
    cancelled_at TIMESTAMP(9) WITH TIME ZONE
);

-- Prevent two tickets from being issued with the same number.
CREATE UNIQUE INDEX uk_ticket_number ON tb_ticket (number);

-- Speeds up fetching waiting tickets of each queue line, in arrival order.
CREATE INDEX ix_ticket_status_priority_issued_at ON tb_ticket (status, priority, issued_at);
